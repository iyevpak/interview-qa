const keys = Object.keys(GLOSSARY).filter((k) => GLOSSARY[k]).sort((a, b) => b.length - a.length);
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const RE = new RegExp(`(?<![\\w.-])(${keys.map(escape).join('|')})(?![\\w-])`, 'g');

/** Renders text with known abbreviations underlined and explained on hover. */
export function Gloss({ children }) {
  if (typeof children !== 'string') return children;
  const parts = children.split(RE);
  return parts.map((p, i) =>
    i % 2 === 1 ? (
      <Tooltip key={i} title={GLOSSARY[p]} arrow>
        <Box component="abbr" tabIndex={0} sx={{ textDecoration: 'underline dotted', textUnderlineOffset: 3, cursor: 'help' }}>{p}</Box>
      </Tooltip>
    ) : p,
  );
}

/** Unique abbreviations found in the given texts, in order. */
export function findTerms(...texts) {
  const found = new Set();
  for (const t of texts) if (typeof t === 'string') for (const m of t.matchAll(RE)) found.add(m[1]);
  return [...found];
}
